#!/usr/bin/env sh
# Starts Uros under Bochs (a pure x86 interpreter, independent of QEMU TCG).
#
# Builds a GRUB ISO with kernel + bootstrap + bundle as multiboot modules,
# and uses the existing IDE disk.img as ata0-master for /mach_servers/.
# The serial output (com1) is redirected to a log file so that we can watch
# the boot even if the Bochs window hangs.
#
# Purpose (#192): if the kernel under Bochs behaves as it does under KVM
# (it boots correctly with the original kmem_alloc_wired path restored),
# then the drop of the *ptep stores through the higher-half alias is specific
# to QEMU TCG.  If Bochs shows it too, the bug is in the kernel.
#
# Usage:
#   ./scripts/run-bochs.sh                  # X11 GUI + serial -> file
#   ./scripts/run-bochs.sh --no-disk        # without the IDE ata0-master
#   tail -F uros/build/bochs-serial.log    # in another terminal
set -e

REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd)
# Overridable, like run-qemu.sh: a measurement must be able to run against a
# tree nobody else is rebuilding (#485).  ⚠️ It has to be honoured in EVERY
# script the run touches -- run-qemu.sh alone was not enough, and the first
# attempt booted a kernel from the measurement tree with a bundle from the
# working one.
BUILD_DIR="${UROS_BUILD_DIR:-$REPO_ROOT/uros/build}"
KERNEL="$BUILD_DIR/export/uros/boot/mach_kernel"
ARCH="$(cat "$BUILD_DIR/uros-arch" 2>/dev/null || uname -m)"   # #404 stamp
BOOTSTRAP="$BUILD_DIR/export/uros/$ARCH/user/sbin/bootstrap"
BUNDLE="$BUILD_DIR/bootstrap.bundle"
DISK_IMG="$BUILD_DIR/disk.img"

ISO_DIR="$BUILD_DIR/bochs-iso"
ISO_IMG="$BUILD_DIR/uros.iso"
BOCHSRC="$BUILD_DIR/bochsrc"
SERIAL_LOG="$BUILD_DIR/bochs-serial.log"

USE_DISK=true
while [ $# -gt 0 ]; do
    case "$1" in
        --no-disk) USE_DISK=false; shift ;;
        *) echo "Unknown flag: $1" >&2; exit 2 ;;
    esac
done

for f in "$KERNEL" "$BOOTSTRAP" "$BUNDLE"; do
    [ -f "$f" ] || { echo "ERROR: missing $f (build first)"; exit 1; }
done
if [ "$USE_DISK" = true ] && [ ! -f "$DISK_IMG" ]; then
    echo "WARNING: $DISK_IMG not found; using --no-disk"
    USE_DISK=false
fi

# 1) Staging the GRUB ISO ------------------------------------------------------
rm -rf "$ISO_DIR"
mkdir -p "$ISO_DIR/boot/grub"
cp "$KERNEL"    "$ISO_DIR/boot/mach_kernel"
cp "$BOOTSTRAP" "$ISO_DIR/boot/bootstrap"
cp "$BUNDLE"    "$ISO_DIR/boot/bootstrap.bundle"

cat >"$ISO_DIR/boot/grub/grub.cfg" <<'GRUB'
set timeout=0
set default=0
serial --unit=0 --speed=9600
terminal_input  console serial
terminal_output console serial

menuentry "Uros (Bochs)" {
    multiboot /boot/mach_kernel
    module    /boot/bootstrap
    module    /boot/bootstrap.bundle
    boot
}
GRUB

echo "Building ISO: $ISO_IMG"
grub-mkrescue -o "$ISO_IMG" "$ISO_DIR" 2>&1 | tail -3

# 2) bochsrc -----------------------------------------------------------------
# Find the BIOS files (Arch puts them in /usr/local/share/bochs).
BX_SHARE=/usr/local/share/bochs
[ -d "$BX_SHARE" ] || BX_SHARE=/usr/share/bochs
ROMBIOS="$BX_SHARE/BIOS-bochs-latest"
VGABIOS="$BX_SHARE/VGABIOS-lgpl-latest.bin"
[ -f "$ROMBIOS" ] || { echo "ERROR: missing $ROMBIOS"; exit 1; }
[ -f "$VGABIOS" ] || { echo "ERROR: missing $VGABIOS"; exit 1; }

DISK_LINE=""
if [ "$USE_DISK" = true ]; then
    DISK_BYTES=$(stat -c %s "$DISK_IMG")
    DISK_SECTORS=$(( DISK_BYTES / 512 ))
    DISK_CYL=$(( DISK_SECTORS / (16 * 63) ))
    DISK_LINE="ata0-master: type=disk, path=\"$DISK_IMG\", mode=flat, cylinders=$DISK_CYL, heads=16, spt=63"
fi

cat >"$BOCHSRC" <<EOF
# Auto-generated by scripts/run-bochs.sh
megs: 512
romimage:    file=$ROMBIOS
vgaromimage: file=$VGABIOS

cpu: model=corei7_sandy_bridge_2600k, count=1, ips=50000000, reset_on_triple_fault=0

ata0: enabled=1, ioaddr1=0x1f0, ioaddr2=0x3f0, irq=14
$DISK_LINE

ata1: enabled=1, ioaddr1=0x170, ioaddr2=0x370, irq=15
ata1-master: type=cdrom, path="$ISO_IMG", status=inserted

boot: cdrom, disk
floppy_bootsig_check: disabled=0

com1: enabled=1, mode=file, dev="$SERIAL_LOG"

display_library: x
log: -
panic: action=ask
error: action=report
info: action=report
debug: action=ignore

clock: sync=none, time0=local
EOF

echo "Bochsrc:    $BOCHSRC"
echo "Serial log: $SERIAL_LOG"
echo
echo "Starting Bochs.  In another terminal:"
echo "    tail -F $SERIAL_LOG"
echo

: > "$SERIAL_LOG"
# Bochs on Arch is built with --enable-debugger, so at startup it enters
# the "<bochs:1>" prompt waiting for a command on stdin.  We feed it a
# continuous stream of `c` (continue) so that it does not stop at the first
# break and does not hang on EOF if a panic happens later.
exec yes c | bochs -q -f "$BOCHSRC"
