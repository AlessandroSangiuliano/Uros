/*
 * libposix-uros — Mach exception ports → POSIX hw signals (#253 /
 * Phase 4b).
 *
 * The kernel posts EXC_BAD_ACCESS / EXC_BAD_INSTRUCTION /
 * EXC_ARITHMETIC / EXC_BREAKPOINT messages to whatever port we
 * install via task_set_exception_ports.  Without one, the kernel
 * falls back to the host default exception port — which on Uros
 * means the task is killed by the kernel and you get no useful
 * diagnostic.  Worse, in the wrong moment, the kernel can panic.
 *
 * This module installs a dedicated exception port owned by the task
 * itself, spins a Mach thread that drains incoming mach_msg into the
 * MIG-generated `exc_server` demux, and turns every hw trap into a
 * one-line console diagnostic followed by a clean task_terminate.
 *
 * Phase 4b is deliberately strict — "log and die".  Doing user-handler
 * dispatch on hw signals (sa_sigaction with siginfo_t, sigreturn,
 * thread-state munging to retry the faulting instruction) requires
 * machinery POSIX gets from sigreturn(3) and we don't want to land
 * here without a real testing story.  Phase 4c can take that on.
 *
 * Author: Alessandro Sangiuliano (Slex) <alex22_7@hotmail.com>
 * License: MIT
 */

