/* ------------------------------------------------------------------ */
/* Exception thread main loop                                          */
/* ------------------------------------------------------------------ */

void
__uros_exc_loop(void)
{
    /* Generous buffers — exc.defs sends small messages but we leave
     * room for trailers and future state-bearing variants. */
    char in_buf[2048];
    char out_buf[2048];

    for (;;) {
        mach_msg_header_t *in  = (mach_msg_header_t *)in_buf;
        mach_msg_header_t *out = (mach_msg_header_t *)out_buf;

        kern_return_t kr = mach_msg(in,
                                    MACH_RCV_MSG,
                                    0,
                                    sizeof(in_buf),
                                    __uros_exc_port,
                                    MACH_MSG_TIMEOUT_NONE,
                                    MACH_PORT_NULL);
        if (kr != KERN_SUCCESS)
            continue;

        boolean_t handled = exc_server(in, out);
        if (!handled)
            continue;

        /* Send the demux's reply (carries the kern_return_t from our
         * catch_exception_raise back to the kernel's exception path). */
        (void)mach_msg(out,
                       MACH_SEND_MSG,
                       out->msgh_size,
                       0,
                       MACH_PORT_NULL,
                       MACH_MSG_TIMEOUT_NONE,
                       MACH_PORT_NULL);
    }
}

/* ------------------------------------------------------------------ */
/* Init                                                                */
/* ------------------------------------------------------------------ */

void
__uros_exceptions_init(void)
{
    kern_return_t kr;

    /* 1. Allocate the receive right the kernel will mach_msg into. */
    kr = mach_port_allocate(mach_task_self(),
                            MACH_PORT_RIGHT_RECEIVE, &__uros_exc_port);
    if (kr != KERN_SUCCESS)
        return;
    (void)mach_port_insert_right(mach_task_self(),
                                 __uros_exc_port, __uros_exc_port,
                                 MACH_MSG_TYPE_MAKE_SEND);

    /* 2. Install it as the all-purpose exception handler for the
     * task.  EXCEPTION_DEFAULT → kernel sends exception_raise (msgid
     * 2401) with thread + task identity; we don't need the state-
     * bearing variants until Phase 4c. */
    kr = task_set_exception_ports(mach_task_self(),
                                  EXC_MASK_ALL,
                                  __uros_exc_port,
                                  EXCEPTION_DEFAULT,
                                  i386_THREAD_STATE);
    if (kr != KERN_SUCCESS) {
        (void)mach_port_destroy(mach_task_self(), __uros_exc_port);
        __uros_exc_port = MACH_PORT_NULL;
        return;
    }

    /* 3. Spawn the exception thread.  Same recipe as the signal
     * thread (signals.c spawn_handler_thread) but a different entry. */
    vm_address_t stack = 0;
    kr = vm_allocate(mach_task_self(), &stack, UROS_EXC_STACK_SIZE, TRUE);
    if (kr != KERN_SUCCESS)
        return;

    extern void __uros_sig_thread_die(void);
    uint32_t *sp = (uint32_t *)(stack + UROS_EXC_STACK_SIZE);
    sp -= 4;                                            /* alignment slack */
    *--sp = (uint32_t)__uros_sig_thread_die;            /* fake return */

    struct i386_thread_state state;
    for (size_t i = 0; i < sizeof state / sizeof(int); i++)
        ((int *)&state)[i] = 0;
    state.eip = (int)__uros_exc_thread_entry;
    state.uesp = (int)sp;
    state.cs   = 0x17;
    state.ds = state.es = state.ss = state.fs = state.gs = 0x1f;
    state.efl  = 0x202;

    thread_act_t thread;
    (void)thread_create_running(mach_task_self(),
                                i386_THREAD_STATE,
                                (thread_state_t)&state,
                                i386_THREAD_STATE_COUNT,
                                &thread);
}
