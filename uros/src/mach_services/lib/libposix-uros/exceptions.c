/* From signals.c — reused so the exception thread can stop printing in
 * the middle of a SIG_DFL terminate path.  Not currently used here but
 * kept handy. */
extern unsigned int __uros_my_pid;

#define UROS_EXC_STACK_SIZE  (16 * 1024)

mach_port_t  __uros_exc_port = MACH_PORT_NULL;

/* ------------------------------------------------------------------ */
/* MIG demux entry point and its stubs                                 */
/* ------------------------------------------------------------------ */

/* Generated by exc.defs MIG — links exc_server() into libmach_core. */
extern boolean_t exc_server(mach_msg_header_t *in, mach_msg_header_t *out);

/*
 * Map a Mach exception (with its code array) to the POSIX signal a
 * Linux kernel would have raised for the same condition.  Used only
 * for the diagnostic — Phase 4b terminates regardless of mapping.
 */
static const char *
exc_to_name(int exc, const int *code, int codeCnt, int *out_signo)
{
    (void)code; (void)codeCnt;
    switch (exc) {
    case EXC_BAD_ACCESS:      *out_signo = 11; return "SIGSEGV";
    case EXC_BAD_INSTRUCTION: *out_signo =  4; return "SIGILL";
    case EXC_ARITHMETIC:      *out_signo =  8; return "SIGFPE";
    case EXC_EMULATION:       *out_signo =  4; return "SIGILL";
    case EXC_SOFTWARE:        *out_signo =  6; return "SIGABRT";
    case EXC_BREAKPOINT:      *out_signo =  5; return "SIGTRAP";
    case EXC_SYSCALL:
    case EXC_MACH_SYSCALL:    *out_signo =  6; return "SIGSYS";
    case EXC_RPC_ALERT:       *out_signo = 14; return "SIGALRM";
    default:                  *out_signo = 11; return "SIG?";
    }
}

kern_return_t
catch_exception_raise(mach_port_t exception_port,
                      mach_port_t thread,
                      mach_port_t task,
                      exception_type_t exception,
                      exception_data_t code,
                      mach_msg_type_number_t codeCnt)
{
    (void)exception_port;

    int signo = 0;
    const char *name = exc_to_name((int)exception, (const int *)code,
                                   (int)codeCnt, &signo);

    /* The subcode (typically code[1]) is the faulting address for
     * EXC_BAD_ACCESS; for EXC_ARITHMETIC it's the operand or 0.  Keep
     * the format compact — one line is enough to diagnose. */
    unsigned long subcode = codeCnt >= 2 ? (unsigned long)code[1] : 0;
    int           sub0    = codeCnt >= 1 ? (int)code[0] : 0;

    printf("(libposix-uros): hw exception %d (%s) thread=0x%x "
           "code=%d subcode=0x%lx — task terminating\n",
           (int)exception, name, (unsigned)thread, sub0, subcode);

    (void)signo;     /* reserved for Phase 4c user handler dispatch */
    (void)task_terminate(task);
    return KERN_SUCCESS;
}

/*
 * We installed the port with EXCEPTION_DEFAULT behavior, so the kernel
 * always sends exception_raise (msgid 2401).  The other two demux
 * callbacks must still exist for the linker to resolve exc_server(),
 * but they're never reached at runtime.  Return KERN_FAILURE so a
 * misconfigured port falls back to the default kernel handling.
 */
kern_return_t
catch_exception_raise_state(mach_port_t exception_port,
                            exception_type_t exception,
                            exception_data_t code,
                            mach_msg_type_number_t codeCnt,
                            int *flavor,
                            thread_state_t old_state,
                            mach_msg_type_number_t old_stateCnt,
                            thread_state_t new_state,
                            mach_msg_type_number_t *new_stateCnt)
{
    (void)exception_port; (void)exception; (void)code; (void)codeCnt;
    (void)flavor; (void)old_state; (void)old_stateCnt;
    (void)new_state; (void)new_stateCnt;
    return KERN_FAILURE;
}

